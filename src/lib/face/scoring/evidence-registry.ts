function symmetry(
  metricId: string,
  group: MetricEvidence["group"],
  harmoniousMax: number,
  sigma: number,
  reliability: number,
  budget: string[],
): MetricEvidence {
  return {
    metricId,
    group,
    view: "front",
    scoringShape: "lower-is-better",
    bands: {
      neutral: {
        aestheticTarget: range(0, Math.min(1.2, harmoniousMax * 0.35)),
        harmoniousRange: range(0, harmoniousMax),
        sigmaLow: sigma,
        sigmaHigh: sigma,
      },
    },
    uncertainty: Math.min(0.8, harmoniousMax * 0.2),
    evidenceType: "direct-attractiveness",
    evidenceTier: 1,
    evidenceLevel: "moderate",
    measurementReliability: reliability,
    formulaCompatibility: 0.45,
    scoreEligible: true,
    perspectiveSensitive: false,
    sourcePopulation: "Attractiveness experiments on symmetry and averageness, not a single demographic cutoff",
    references: SYMMETRY_REFS,
    limitations: SYMMETRY_LIMITS,
    formulaCompatibilityNotes: [
      "Direction (lower asymmetry scores higher) follows the experiments. The percent scale is a HarmonyLabs photographic summary.",
    ],
    accuracyBudget: budget,
  };
}

function extremeness(
  metricId: string,
  group: MetricEvidence["group"],
  min: number,
  max: number,
  sigma: number,
  reliability: number,
  perspectiveSensitive: boolean,
  notes: string[],
  budget: string[],
): MetricEvidence {
  return {
    metricId,
    group,
    view: "front",
    scoringShape: "extremeness",
    bands: { neutral: { harmoniousRange: range(min, max), sigmaLow: sigma, sigmaHigh: sigma } },
    evidenceType: "anthropometric-proportion",
    evidenceTier: 3,
    evidenceLevel: "low",
    measurementReliability: reliability,
    formulaCompatibility: 0.7,
    scoreEligible: true,
    perspectiveSensitive,
    sourcePopulation: "Cross-population anthropometry. No ancestry is inferred, and the band is intentionally wide.",
    references: [FANG_2011, FARKAS_1994, KHOSHAB_2021, LANGLOIS_2000],
    limitations: [
      "There is no formula-compatible attractiveness optimum for this ratio.",
      "The interval is a disproportion screen. Values inside it are not ranked toward a population mean.",
      "Equal neoclassical canons and phi are not targets.",
      ...notes,
    ],
    formulaCompatibilityNotes: notes,
    accuracyBudget: budget,
  };
}

function informational(
  metricId: string,
  group: MetricEvidence["group"],
  view: MetricEvidence["view"],
  min: number,
  max: number,
  limitations: string[],
  notes: string[],
  budget: string[],
  references: MetricEvidence["references"] = CONTEXT,
): MetricEvidence {
  return {
    metricId,
    group,
    view,
    scoringShape: "extremeness",
    bands: { neutral: display(min, max, Math.max(0.05, (max - min) / 6)) },
    evidenceType: "unsupported",
    evidenceTier: 4,
    evidenceLevel: "insufficient",
    measurementReliability: 0.45,
    formulaCompatibility: 0.3,
    scoreEligible: false,
    perspectiveSensitive: view === "profile",
    sourcePopulation: "Not used as a Harmony reference",
    references,
    limitations,
    formulaCompatibilityNotes: notes,
    accuracyBudget: budget,
  };
}

