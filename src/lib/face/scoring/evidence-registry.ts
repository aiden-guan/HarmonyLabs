function range(min: number, max: number, center?: number): NumericBand {
  return center === undefined ? { min, max } : { min, max, center };
}

function display(min: number, max: number, sigma: number): PresentationBands {
  return {
    harmoniousRange: range(min, max),
    sigmaLow: sigma,
    sigmaHigh: sigma,
  };
}

